"""The other dungeons' legendaries' base items (mod-legendary Definitions 4-24) as world SQL: appended to
modules/mod-legendary/data/sql/db-world/base/legendary_items.sql between its markers.

Each base is an Item.dbc row with no template of its own (the custom item ids rule): its template is copied from the
item whose look it wears (localTools/patchSinisterStrike.ps1 $legendaryItems), every stat, spell, socket and limit
stripped - a copy rolls its own (character_legendary) - and its class, subclass, material, slot and sheath set to the
row's, which the server enforces over the template.

Usage: python localTools/legendary/buildLegendaryItemSql.py
"""

import struct
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SQL = REPO / "modules" / "mod-legendary" / "data" / "sql" / "db-world" / "base" / "legendary_items.sql"
ITEM_DBC = REPO / "server" / "Data" / "dbc" / "Item.before-paragon-glyphs.dbc"
BEGIN = "-- BEGIN generated by localTools/legendary/buildLegendaryItemSql.py"
END = "-- END generated"

# Base item, the template its look comes from, its name: French first (the server's own language), English second
