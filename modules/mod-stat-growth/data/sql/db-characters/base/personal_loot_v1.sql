CREATE TABLE IF NOT EXISTS `mod_personal_loot_roll` (
  `item_guid` INT UNSIGNED NOT NULL,
  `rarity` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `custom_name` VARCHAR(160) NOT NULL,
  `rolled_class` TINYINT UNSIGNED NOT NULL,
  `affix1_type` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `affix1_value` INT UNSIGNED NOT NULL DEFAULT 0,
  `affix2_type` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `affix2_value` INT UNSIGNED NOT NULL DEFAULT 0,
  `affix3_type` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `affix3_value` INT UNSIGNED NOT NULL DEFAULT 0,
  `affix4_type` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `affix4_value` INT UNSIGNED NOT NULL DEFAULT 0,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`item_guid`),
  KEY `idx_rarity` (`rarity`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
